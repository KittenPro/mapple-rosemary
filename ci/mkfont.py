def rows(ch):
    bits = GLYPHS.get(ch.upper() if ch.isalpha() else ch, GLYPHS.get(ch, []))
    out = []
    for i in range(16):
        src = bits[i - 2] if 2 <= i < 2 + len(bits) else 0
        out.append((src & 0x1F) << 1)
    return out


def main():
    dest = sys.argv[1] if len(sys.argv) > 1 else "font8x16.h"
    lines = [
        "#ifndef FONT8X16_H",
        "#define FONT8X16_H",
        "/* made by ci/mkfont.py; not a vendor or system font */",
        "static const unsigned char font8x16[95][16] = {",
    ]
    for c in range(0x20, 0x7F):
        lines.append("\t{" + ",".join("0x%02x" % b for b in rows(chr(c))) + "},")
    lines += ["};", "#endif", ""]
    open(dest, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
